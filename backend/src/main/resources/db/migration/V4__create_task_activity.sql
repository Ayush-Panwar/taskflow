CREATE TABLE task_activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT                   NOT NULL,
    actor_id    BIGINT                   NOT NULL,
    from_status VARCHAR(20)              NOT NULL,
    to_status   VARCHAR(20)              NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_activity_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_activity_actor FOREIGN KEY (actor_id) REFERENCES users (id)
);

CREATE INDEX idx_task_activity_task ON task_activity (task_id, occurred_at);
